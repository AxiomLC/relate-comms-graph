/**
 * The glyph for one node, chosen by its KIND and then its platform.
 *
 * The glyph for one node, chosen by its KIND and then its platform.
 *
 * Four routes, one per `iconKind`:
 *
 *   - `platform`  — a Thread draws its source's glyph.
 *   - `person`    — a Correspondent draws the person glyph, neutral grey if merged.
 *   - `entity`    — Person / Place / Organization / Product draw their own set.
 *   - `null`      — no glyph; the node draws the base filled circle.
 *
 * A glyph cannot be tinted at runtime, so each one needs a file per platform colour.
 * That is why the entity sets are generated (`scripts/build_entity_icons.py`) rather
 * than hand-written, and why a kind with no artwork is a circle rather than an
 * invented glyph.
 */
export function nodeIcon(type, platform, merged = false) {
  const kind = NODE_TYPES[type]?.iconKind;
  if (kind === "platform") return platformIcon(platform);
  // A merged Correspondent gets the neutral grey glyph, not its first platform's.
  // The third argument is explicit rather than folded into `platform` because a
  // platform named "merged" must never be able to hijack the lookup.
  if (kind === "person") return personIcon(merged ? "merged" : platform);
  // The extracted kinds (`Person`, `Place`, `Organization`, `Product`) each carry
  // their own glyph set, selected the same way.
  if (kind === "entity") return entityIcon(type, platform, merged);
  return null;
}

/**
 * The kind class for a node, or null.
 *
 * A thread is not a kind — its glyph already says which platform it is — so it gets
 * no class. A kind with a glyph carries `person`; the four extracted kinds carry
 * nothing, because they have no glyph and the class exists only to pick one.
 */
export function kindClass(type) {
  const kind = NODE_TYPES[type]?.iconKind;
  return kind && kind !== "platform" ? kind : null;
}

